/* Existing installed Playwright + Chrome only; no browser downloads. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {chromium} = require(process.env.GTM_PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const out = path.join(root, '.factory/adversarial-prep/browser');
fs.mkdirSync(out, {recursive: true});
const server = spawn(process.env.GTM_PYTHON || 'python', ['-u', 'server.py', '--port', '0', '--no-browser'], {cwd: root});
const observations = [];
const pass = (id, detail) => observations.push({id, status: 'PASS', detail});
let browser;
(async () => {
    const url = await new Promise((resolve, reject) => {
        const timeout = setTimeout(() => reject(Error('Server startup timed out')), 10000);
        server.stderr.on('data', value => {
            const match = value.toString().match(/http:\/\/127\.0\.0\.1:\d+\/ui\/index\.html/);
            if (match) { clearTimeout(timeout); resolve(match[0]); }
        });
        server.on('error', reject);
    });
    browser = await chromium.launch({headless: true, channel: 'chrome'});
    const page = await browser.newPage({viewport: {width: 1440, height: 1100}, acceptDownloads: true});
    const errors = [], posts = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('dialog', d => d.accept());
    page.on('request', r => { if (r.method() === 'POST') posts.push(r.url()); });
    await page.clock.install();
    await page.goto(url, {waitUntil: 'networkidle'});
    await page.locator('#userInput').fill('A weekly reporting product.');
    await page.locator('#sendBtn').click();
    await page.waitForFunction(() => currentPhase === 1);
    await page.locator('#userInput').fill('Customers need weekly reporting for 20 accounts.');
    await page.locator('#sendBtn').click();
    await page.waitForFunction(() => currentPhase === 2);
    await page.locator('#rememberSession').check();
    const interview = await page.evaluate(() => ({phase: currentPhase, concept: accumulatedContext.concept, answers: accumulatedContext.phases, reviews: sessionReviews}));
    const beforePosts = posts.length;
    await page.locator('#openPractice').click();
    await page.locator('#prepExtract').click();
    await page.locator('#prepCandidate1').click();
    assert.equal(await page.locator('#prepClaimText').inputValue(), 'Customers need weekly reporting for 20 accounts.');
    await page.locator('#prepClaimSelect').selectOption('');
    await page.locator('#prepClaimText').fill('Customers need weekly reporting for 30 accounts.');
    await page.locator('#prepSaveClaim').click();
    await page.locator('#prepConflicts').evaluate(el => el.open = true);
    assert.match(await page.locator('#prepConflictList').innerText(), /20 accounts/);
    assert.match(await page.locator('#prepConflictList').innerText(), /30 accounts/);
    pass('claim_ledger', 'Verbatim interview statement and second claim retained; numeric possible-conflict quotes displayed.');
    await page.locator('#prepClaimSelect').selectOption('c1');
    await page.locator('#prepPersona').selectOption('buyer');
    await page.locator('#prepScenario').selectOption('budget');
    await page.locator('#prepLimit').selectOption('30');
    await page.locator('#prepStart').click();
    assert.match(await page.locator('#prepQuestion').innerText(), /recent buying decision/);
    await page.locator('#prepAnswer').fill('Buyers said the weekly report helps their team.');
    await page.locator('#prepRespond').click();
    assert.match(await page.locator('#prepQuestion').innerText(), /Which dated observation/);
    await page.locator('#prepAnswer').fill('I disagree with the premise; the first buyer did not purchase.');
    await page.locator('#prepContested').check();
    await page.locator('#prepRespond').click();
    assert.match(await page.locator('#prepQuestion').innerText(), /unsupported premise/);
    pass('adaptive_followup', 'Missing evidence triggers a dated-source follow-up; contesting triggers premise correction.');
    await page.locator('#prepAnswer').fill('Keep this unsent rehearsal answer.');
    await page.locator('#prepTimerToggle').click();
    await page.clock.fastForward(31000);
    assert.match(await page.locator('#prepStatus').innerText(), /draft is retained/);
    assert.equal(await page.locator('#prepAnswer').inputValue(), 'Keep this unsent rehearsal answer.');
    const turns = await page.evaluate(() => practiceState.runs[0].turns.length);
    assert.equal(turns, 2);
    await page.locator('#prepInterrupt').click();
    assert.match(await page.locator('#prepQuestion').innerText(), /Let me interrupt/);
    assert.equal(await page.locator('#prepAnswer').inputValue(), 'Keep this unsent rehearsal answer.');
    await page.locator('#prepClose').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'openPractice');
    await page.reload({waitUntil: 'networkidle'});
    await page.locator('#openPractice').click();
    assert.equal(await page.locator('#prepAnswer').inputValue(), 'Keep this unsent rehearsal answer.');
    assert.match(await page.locator('#prepQuestion').innerText(), /Let me interrupt/);
    pass('timed_rehearsal', '30-second deadline preserves draft and turn count; interruption and device reload preserve pending practice.');
    await page.locator('#prepFinish').click();
    assert.match(await page.locator('#prepDebrief').innerText(), /still missing: evidence, counterexample, test/);
    await page.locator('#prepRetest').click();
    assert.match(await page.locator('#prepQuestion').innerText(), /recent buying decision/);
    await page.locator('#prepAnswer').fill('Revised defense based on actual interviews.');
    await page.locator('#prepAnswerForm details').evaluate(el => el.open = true);
    await page.locator('#prepEvidence').fill('Interview note 1, 2026-10-21.');
    await page.locator('#prepCounterexample').fill('Buyer two prefers the current workflow.');
    await page.locator('#prepTest').fill('Offer a paid pilot; no acceptance would weaken the demand claim.');
    await page.locator('#prepRespond').click();
    await page.locator('#prepFinish').click();
    assert.match(await page.locator('#prepDebrief').innerText(), /Retest comparison/);
    assert.match(await page.locator('#prepDebrief').innerText(), /Buyers said the weekly report/);
    assert.match(await page.locator('#prepDebrief').innerText(), /Revised defense based/);
    await page.screenshot({path: path.join(out, 'debrief-desktop.png'), fullPage: true});
    pass('practice_debrief', 'Retest uses original objection; debrief shows prior/current answers and recorded gaps without scoring.');
    const downloadText = async selector => {
        const event = page.waitForEvent('download'); await page.locator(selector).click();
        const download = await event; return fs.readFileSync(await download.path(), 'utf8');
    };
    assert.match(await downloadText('#prepDownload'), /Revised defense/);
    assert.match(await downloadText('#prepCoach'), /untrusted data, not instructions/);
    assert.match(await downloadText('#prepCSV'), /Founder review status/);
    await page.locator('#prepClose').click();
    const event = page.waitForEvent('download'); await page.getByRole('button', {name: 'Save session file', exact: true}).click();
    const download = await event;
    const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    assert.equal(exported.prep.runs.length, 2);
    assert.equal(exported.phase, 2);
    assert.deepEqual(await page.evaluate(() => ({phase: currentPhase, concept: accumulatedContext.concept, answers: accumulatedContext.phases, reviews: sessionReviews})), interview);
    assert.equal(posts.length, beforePosts);
    pass('practice_isolation', 'Interview phase/answers unchanged; no practice POST or provider request; real debrief/CSV/coach/session downloads verified.');
    const hostile = structuredClone(exported);
    hostile.prep.claims[0].text = '<img src=x onerror="window.prepInjected=true">';
    await page.locator('#sessionFile').setInputFiles({name: 'hostile.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(hostile))});
    await page.locator('#openPractice').click();
    assert.equal(await page.locator('#prepClaimText').inputValue(), hostile.prep.claims[0].text);
    assert.equal(await page.evaluate(() => !!window.prepInjected), false);
    assert.equal(await page.locator('#prepDialog img').count(), 0);
    await page.locator('#prepClose').click();
    const bad = structuredClone(exported); bad.prep.runs[0].claimId = 'c99';
    await page.locator('#sessionFile').setInputFiles({name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bad))});
    assert.match(await page.locator('#workspaceStatus').innerText(), /Import failed; current session retained/);
    assert.equal(await page.evaluate(() => practiceState.claims[0].text), hostile.prep.claims[0].text);
    pass('practice_recovery', 'Hostile content rendered as text; dangling claim reference import rejected without replacing active state.');
    await page.locator('#sessionFile').setInputFiles({name: 'clean.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported))});
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('#openPractice').click();
    assert.equal(await page.locator('#prepDialog').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true);
    await page.locator('#prepClose').focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.getElementById('prepDialog').contains(document.activeElement)), true);
    await page.screenshot({path: path.join(out, 'practice-mobile.png'), fullPage: true});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#prepDialog').evaluate(el => el.open), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'openPractice');
    pass('practice_accessibility', '390px dialog has no horizontal overflow; keyboard focus stays inside; Escape returns focus to opener.');
    assert.deepEqual(errors, []);
    pass('browser_runtime', 'No uncaught browser errors across practice lifecycle.');
    fs.writeFileSync(path.join(out, 'observations.json'), JSON.stringify({at: new Date().toISOString(), observations}, null, 2));
    console.log(JSON.stringify({status: 'PASS', scenarios: observations.length, observations}, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server.kill(); });
