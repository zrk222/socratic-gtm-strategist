const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {chromium} = require(process.env.GTM_PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const out = path.join(root, process.env.GTM_BROWSER_OUTPUT || '.factory/guided-workflow/browser');
fs.mkdirSync(out, {recursive:true});
const server = spawn('python', ['-u', 'server.py', '--port', '0', '--no-browser'], {cwd:root});
let browser;
(async () => {
    const url = await new Promise((resolve,reject) => {
        const timer = setTimeout(() => reject(Error('Startup timed out')),10000);
        server.stderr.on('data',d => { const m=d.toString().match(/http:\/\/127\.0\.0\.1:\d+\/ui\/index\.html/); if(m){clearTimeout(timer);resolve(m[0]);} });
    });
    browser = await chromium.launch({headless:true,channel:'chrome'});
    const page = await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url,{waitUntil:'networkidle'});
    assert.equal(await page.locator('#workflowExtras').evaluate(el=>el.open),false);
    assert.equal(await page.locator('#workflowPrimary').isVisible(),false);
    assert.equal(await page.locator('#ideaFieldLabel').isVisible(),true);
    assert.match(await page.locator('#workflowExplainer').innerText(),/What:[\s\S]*How:[\s\S]*When:/);
    await page.getByRole('button',{name:'Help me start',exact:true}).click();
    assert.match(await page.locator('#userInput').inputValue(),/\[customer\]/);
    await page.locator('#userInput').fill('My own draft');
    await page.getByRole('button',{name:'Help me start',exact:true}).click();
    assert.equal(await page.locator('#userInput').inputValue(),'My own draft');
    assert.equal(await page.evaluate(()=>currentPhase),0);
    await page.locator('#userInput').fill('');
    await page.locator('#userInput').click();
    assert.equal(await page.evaluate(()=>document.activeElement.id),'userInput');
    await page.screenshot({path:path.join(out,'start-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(out,'start-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#userInput').fill('I help agencies prepare weekly client reports.');
    await page.getByRole('button',{name:'Continue with my answer'}).click();
    await page.waitForFunction(()=>currentPhase===1);
    assert.match(await page.locator('#workflowTitle').innerText(),/Question 1 of 8/);
    assert.match(await page.locator('#strategistNudge').innerText(),/how often/);
    await page.getByRole('button',{name:'Not sure yet',exact:true}).click();
    assert.match(await page.locator('#userInput').inputValue(),/I do not know yet/);
    assert.equal(await page.evaluate(()=>currentPhase),1);
    await page.locator('#userInput').fill('Teams need weekly reports; demand is still an assumption.');
    await page.locator('#sendBtn').click();
    await page.waitForFunction(()=>currentPhase===2);
    assert.match(await page.locator('#strategistNudge').innerText(),/uncertainty visible/);
    await page.locator('#workflowPractice').click();
    assert.equal(await page.locator('#prepDialog').evaluate(el=>el.open),true);
    assert.equal(await page.locator('#prepLedger').isVisible(),false);
    assert.match(await page.locator('#prepQuestion').innerText(),/Teams need weekly reports/);
    assert.match(await page.locator('#prepQuestion').innerText(),/Skeptical buyer/);
    await page.locator('#prepAnswer').fill('I do not know yet; I need buyer interviews.');
    await page.locator('#prepRespond').click();
    await page.locator('#prepFinish').click();
    assert.equal(await page.locator('#prepDialog').evaluate(el=>el.open),false);
    assert.equal(await page.locator('#workflowPrimary').innerText(),'Download my next steps');
    assert.equal(await page.locator('#userInput').isVisible(),false);
    assert.equal(await page.locator('#strategistShortcuts').isVisible(),false);
    assert.match(await page.locator('#workflowWhen').innerText(),/before your next meeting/);
    const event=page.waitForEvent('download');await page.locator('#workflowPrimary').click();
    const download=await event;
    const notes=fs.readFileSync(await download.path(),'utf8');
    assert.match(notes,/I help agencies/);assert.match(notes,/I do not know yet; I need buyer interviews/);
    assert.equal(await page.evaluate(()=>currentPhase),2);
    await page.screenshot({path:path.join(out,'next-steps-desktop.png'),fullPage:true});
    await page.locator('#workflowExtras > summary').click();
    assert.equal(await page.locator('#reviewAnswersBtn').isVisible(),true);
    const popup=page.waitForEvent('popup');await page.locator('#moreTools').selectOption('simulator');
    const calculator=await popup;await calculator.waitForLoadState('domcontentloaded');
    assert.match(await calculator.locator('.start-guide').innerText(),/optional calculator/);
    await calculator.getByRole('link',{name:'Back to my preparation'}).click();
    await calculator.waitForURL('**/ui/index.html');
    await calculator.close();
    await page.locator('#workflowExtras > summary').click();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(out,'next-steps-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: first-use entry, guided questions, direct practice, next-step download, simulator return and mobile layout.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await browser?.close();server.kill();});
